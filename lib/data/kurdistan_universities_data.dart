  /// Helper to get University by Name or ID
  static UniversityInfo? findUniversity(String? name) {
    if (name == null || name.trim().isEmpty) return null;
    final clean = name.trim().toLowerCase();
    for (final u in universities) {
      if (u.nameKu.toLowerCase().contains(clean) ||
          u.nameEn.toLowerCase().contains(clean) ||
          clean.contains(u.nameKu.toLowerCase()) ||
          u.id == clean) {
        return u;
      }
    }
    return null;
  }

  /// Get departments for a given university name
  static List<String> getDepartmentsFor(String? universityName) {
    final uni = findUniversity(universityName);
    if (uni != null && uni.departments.isNotEmpty) {
      return uni.departments;
    }
    return commonDepartments;
  }
