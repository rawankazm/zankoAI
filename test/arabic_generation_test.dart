import 'package:flutter_test/flutter_test.dart';
import 'package:zanko_ai/services/docx_generator_service.dart';
import 'package:zanko_ai/services/pptx_generator_service.dart';

void main() {
  test('Test Arabic Slide Parsing with various Arabic formats', () {
    const arabicAiSeminar = '''
# 📊 عرض تقديمي: الذكاء الاصطناعي في التعليم الجامعي
### الشريحة رقم 1: الذكاء الاصطناعي في التعليم الجامعي
- **المفهوم والأهمية**: يمثل الذكاء الاصطناعي ثورة علمية وتقنية في تطوير مناهج التعليم الجامعي بنسبة تفوق ٨٥٪.
- **الأطروحة الأساسية**: دمج النماذج اللغوية الكبيرة في بيئات التعلم النشط يعزز الكفاءة والابتكار.
- **الأهداف العامة**: توضيح الفرص الواعدة وتجاوز التحديات المنهجية بكفاءة عالية.
- 🖼️ **التركيز البصري: شبكة عصبية وكتب جامعية متطورة**
- 🎙️ **ملاحظات المتحدث: أهلاً بكم في هذا العرض العلمي الأكاديمي**

### ٢. الأسس النظرية والتطور التاريخي
- **المراحل التطورية**: تحليل النقلات النوعية في النظم الذكية منذ منتصف القرن العشرين.
- **الأطر المفاهيمية**: تصنيف النظريات الأكاديمية الحديثة الداعمة للتعلم الرقمي.
- 🎙️ **ملاحظات المتحدث: ننتقل الآن إلى استعراض الخلفية النظرية**

### ٣. إشكالية البحث والتحديات
- **التحديات الهيكلية**: قيود المناهج التقليدية والافتقار إلى المرونة.
- **الفجوة الرقمية**: تفاوت الجاهزية التقنية بين المؤسسات بنسبة ٤٠٪.

### 🔹 الشريحة رقم 4: الأهداف الاستراتيجية والفرضيات
- رفع الكفاءة الأكاديمية وتقليل الجهد بنسبة ٦٠٪.
- تعزيز مهارات التفكير النقدي لدى الطلاب.

### 🔹 الشريحة 5: منهجية العمل والإطار التطبيقي
- تطبيق المنهج الوصفي التحليلي على عينة من ٥٠٠ طالب.
- استخدام خوارزميات التعلم الآلي في تحليل النتائج.

### 🔹 الشريحة 6: النتائج والتحليل المقارن
- تحقيق تحسن ملحوظ بنسبة ٧٨.٥٪ في سرعة الاستيعاب.
- انخفاض نسبة الأخطاء المنهجية إلى أقل من ٣٪.

### 🔹 الشريحة 7: المناقشة والتوصيات العملية
- أهمية تأهيل الكوادر التدريسية على استخدام الأدوات الذكية.
- صياغة سياسات وضوابط أخلاقية واضحة لحوكمة الذكاء الاصطناعي.

### 🔹 الشريحة 8: الخاتمة وقائمة المراجع
- **الخلاصة العلمية**: دمج التقنيات الحديثة ضرورة حتمية للجامعات المعاصرة.
- **المراجع الأكاديمية**: السامرائي، أحمد (٢٠٢٤). تقنيات التعلم الذكي.
- **شكراً لحضوركم**
''';

    final slides = PptxGeneratorService.parseSlidesFromText(arabicAiSeminar, defaultTitle: 'الذكاء الاصطناعي');
    expect(slides.length, 8);
    expect(slides[0].title.contains('الذكاء الاصطناعي'), true);
    expect(slides[1].title.contains('الأسس النظرية'), true);
    expect(slides[2].title.contains('إشكالية'), true);
    expect(slides[3].title.contains('الأهداف'), true);
    expect(slides[7].bulletPoints.any((b) => b.contains('شكراً لحضوركم')), true);
  });

  test('Test Arabic Report Parsing with textual headers', () {
    const arabicAiReport = '''
### Title: الذكاء الاصطناعي في التعليم العالي
### فهرس المحتويات
1. المقدمة والأهداف البحثية
2. الأسس النظرية والخلفية التاريخية
3. الهيكل الأساسي والمكونات
4. آليات العمل والمنهجية
5. التحليل المعمق والديناميكيات
6. التطبيقات العملية والدراسات الميدانية
7. المقارنة المعيارية ومؤشرات الكفاءة
8. التحديات والاعتبارات الأخلاقية
9. الآفاق المستقبلية والتحولات الذكية
10. الاستنتاجات العلمية والتوصيات

### المحور الأول: المقدمة والأهداف البحثية
يمثل الذكاء الاصطناعي في التعليم العالي نقلة نوعية كبرى في أساليب التدريس والبحث الأكاديمي. يوفر هذا التقرير تحليلاً شاملاً للمفاهيم الأساسية والتحولات الحديثة التي تشهدها الجامعات العالمية في توظيف التقنيات الذكية.
- المفاهيم الجوهرية المرتبطة بالذكاء الاصطناعي
- أهمية التحول الرقمي في المؤسسات الجامعية
- الأهداف الاستراتيجية للتقرير

### المحور الثاني: الأسس النظرية والخلفية التاريخية
يقوم الإطار النظري على مبادئ التعلم الآلي والنماذج الإحصائية المتقدمة. وقد مرت هذه النظم بعدة مراحل تاريخية بدأت في الخمسينيات وتوجت بثورة التعلم العميق في العقد الأخير.

### المحور الثالث: الهيكل الأساسي والمكونات
تتكون المنظومة من ثلاث طبقات رئيسية: طبقة جمع البيانات، وطبقة المعالجة والخوارزميات، وطبقة التطبيقات التفاعلية التي يتعامل معها الطالب والأستاذ.

### المحور الرابع: آليات العمل والمنهجية
تعتمد منهجية البحث على التحليل المقارن والمسح الشامل للتطبيقات الحديثة في كبرى الجامعات، مع قياس الكفاءة التشغيلية والدقة التحليلية.

### المحور الخامس: التحليل المعمق والديناميكيات
أظهرت التحليلات أن استخدام الأنظمة الذكية يسرع من عمليات التقييم الأكاديمي ويقلل الوقت المستغرق في تصحيح الاختبارات وتحليل أداء الطلاب بنسبة تتجاوز ٧٠٪.

### المحور السادس: التطبيقات العملية والدراسات الميدانية
تم تطبيق النماذج في عدة كليات علمية وأظهرت النتائج تحسناً ملحوظاً في تفاعل الطلبة ومشاركتهم الفعالة في الأنشطة البحثية وحل المسائل المعقدة.

### المحور السابع: المقارنة المعيارية ومؤشرات الكفاءة
عند مقارنة المنظومات الذكية بالأساليب التقليدية، تبين تفوقها في مجالات الدقة، والسرعة، والقدرة على استيعاب الفروق الفردية بين المتعلمين.

### المحور الثامن: التحديات والاعتبارات الأخلاقية
تواجه هذه التطبيقات تحديات متعددة أبرزها حماية خصوصية البيانات، ومخاطر التحيز الخوارزمي، وضرورة الحفاظ على النزاهة الأكاديمية.

### المحور التاسع: الآفاق المستقبلية والتحولات الذكية
يتجه مستقبل التعليم الجامعي نحو تخصيص مسارات التعلم التكيفي وتطوير مساعدين أذكياء لكل باحث وطالب لدعم اتخاذ القرار وتوليد المعرفة.

### المحور العاشر: الاستنتاجات العلمية والتوصيات
نستنتج أن الاستثمار في البنية التحتية للذكاء الاصطناعي ضرورة استراتيجية للجامعات. نوصي بتحديث المناهج ووضع أطر تشريعية لحوكمة التقنية.

### المراجع والمصادر
1. السامرائي، أحمد (٢٠٢٤). الذكاء الاصطناعي والتعليم الجامعي. دار الفكر، عمان.
2. العلي، خالد (٢٠٢٥). النظم الذكية في التعليم العالي. مجلة العلوم التربوية، ١٤(٢)، ٥٥-٧٨.
''';

    final report = DocxGeneratorService.parseReportFromText(
      rawText: arabicAiReport,
      title: 'الذكاء الاصطناعي في التعليم العالي',
      studentName: 'أحمد محمود',
      supervisorName: 'د. علي حسن',
      universityName: 'جامعة صلاح الدين',
      departmentName: 'كلية العلوم',
      academicYear: '2025 - 2026',
      languageCode: 'ar',
    );

    expect(report.pages.length, 8);
    // Page 3 contains Section 1 & Section 2
    final page3 = report.pages[2];
    expect(page3.sections.length, 2);
    expect(page3.sections[0].title.contains('المقدمة'), true);
    expect(page3.sections[0].content.contains('يمثل الذكاء الاصطناعي'), true);
    expect(page3.sections[1].title.contains('الأسس النظرية'), true);

    // Page 7 contains Section 9 & Section 10
    final page7 = report.pages[6];
    expect(page7.sections.length, 2);
    expect(page7.sections[1].title.contains('الاستنتاجات'), true);

    // Page 8 contains References
    final page8 = report.pages[7];
    expect(page8.bulletPoints.length, greaterThanOrEqualTo(2));
    expect(page8.bulletPoints[0].contains('السامرائي'), true);
  });
}
